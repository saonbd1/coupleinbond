// Adds or refreshes <lastmod> on every entry in public/sitemap.xml.
//
// The sitemap is a hand-maintained file that the daily poll pipeline appends to, so
// without this it carried no modification dates at all and Google had no signal for
// recrawl pacing on a young domain. Dates come from the content itself, in this order:
//
//   /blog-posts/<slug>.html  dateModified (else datePublished) in src/content/blog
//   /polls/<slug>.html       the YYYYMMDD stamp in the slug, else the file's git date
//   everything else          the git date of the source file that renders the page
//
// Run whenever content changes:
//   npm run sitemap:lastmod          # rewrite in place
//   npm run sitemap:lastmod -- --dry # print the table, change nothing
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const SITEMAP = path.join(ROOT, 'public', 'sitemap.xml');
const dryRun = process.argv.includes('--dry');

const gitDate = (relPath) => {
  try {
    // %as = author date, short form (YYYY-MM-DD). Empty output means the path was
    // never committed, in which case the caller skips the entry.
    return execFileSync('git', ['-C', ROOT, 'log', '-1', '--format=%as', '--', relPath], { encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
};

const frontmatterField = (relPath, keys) => {
  const file = path.join(ROOT, relPath);
  if (!existsSync(file)) return '';
  const text = readFileSync(file, 'utf8').split('\n').slice(0, 60).join('\n');
  for (const key of keys) {
    const m = text.match(new RegExp(`^${key}:\\s*["']?([^"'\\n]+)`, 'm'));
    if (m && m[1].trim()) return m[1].trim().slice(0, 10);
  }
  return '';
};

const isIsoDate = (s) => /^\d{4}-\d{2}-\d{2}$/.test(s);

// Adding a post shifts every page of the archive, so the pagination listings change on
// the newest publication date rather than the date the listing template was edited.
const newestBlogDate = (() => {
  let newest = '';
  const dir = path.join(ROOT, 'src', 'content', 'blog');
  for (const name of readdirSync(dir)) {
    if (!name.endsWith('.md')) continue;
    const value = frontmatterField(path.join('src', 'content', 'blog', name), ['dateModified', 'datePublished']);
    if (isIsoDate(value) && value > newest) newest = value;
  }
  return newest;
})();

// Maps a sitemap path to the last date we can actually prove for it.
function lastmodFor(sitePath) {
  const rel = sitePath.replace(/^\/+/, '') || 'index.html';

  const post = rel.match(/^blog-posts\/(.+)\.html$/);
  if (post) {
    const fromFm = frontmatterField(path.join('src', 'content', 'blog', `${post[1]}.md`), ['dateModified', 'datePublished']);
    if (isIsoDate(fromFm)) return fromFm;
    return gitDate(path.join('src/content/blog', `${post[1]}.md`));
  }

  const poll = rel.match(/^polls\/(.+)\.html$/);
  if (poll) {
    const stamp = poll[1].match(/(\d{4})(\d{2})(\d{2})$/);
    // Slugs generated by the daily pipeline end in the publish date.
    if (stamp) return `${stamp[1]}-${stamp[2]}-${stamp[3]}`;
    return gitDate(path.join('src/content/polls', `${poll[1]}.md`));
  }

  const page = rel.match(/^blog\/page\/(\d+)\.html$/);
  if (page) return newestBlogDate || gitDate('src/components/BlogIndex.astro');

  const candidates = [
    path.join('public', rel),
    path.join('src', 'pages', `${rel.replace(/\.html$/, '')}.astro`),
  ].filter((p) => existsSync(path.join(ROOT, p)));
  if (!candidates.length) return '';
  return gitDate(candidates[0].split(path.sep).join('/'));
}

// One <url> per line, as the pipeline writes them.
const ENTRY = /^([ \t]*)<url><loc>(https?:\/\/[^<]+)<\/loc>(?:<lastmod>[^<]*<\/lastmod>)?<\/url>[ \t]*$/;

const source = readFileSync(SITEMAP, 'utf8');
const rows = [];
// Splitting with a capture group keeps the line breaks as their own array items, so
// every entry is rewritten with the exact ending it already had. The file mixes the
// CRLF a Windows checkout produces with the LF lines the GitHub Action appends, and
// rewriting it with a single global regex used to collapse that into blank lines.
const output = source
  .split(/(\r\n|\n)/)
  .map((chunk) => {
    const m = ENTRY.exec(chunk);
    if (!m) return chunk;
    let sitePath;
    try {
      sitePath = new URL(m[2]).pathname;
    } catch {
      return chunk;
    }
    const date = lastmodFor(sitePath);
    rows.push(`${(date || '-').padEnd(12)} ${sitePath}`);
    if (!date) return chunk;
    return `${m[1]}<url><loc>${m[2]}</loc><lastmod>${date}</lastmod></url>`;
  })
  .join('');

const withDate = rows.filter((r) => !r.startsWith('-')).length;
console.log(rows.join('\n'));
console.log(`\nentries: ${rows.length} | dated: ${withDate} | undated: ${rows.length - withDate}`);
if (rows.length - withDate) console.log('  (entries with no provable date keep their existing shape)');

if (dryRun) {
  console.log('\n--dry: sitemap.xml not written.');
} else {
  writeFileSync(SITEMAP, output, 'utf8');
  console.log('\nwrote public/sitemap.xml');
}
